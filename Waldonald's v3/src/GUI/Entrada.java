    private void ajustarImagenPantallaCompleta() {
        java.awt.Toolkit toolkit = java.awt.Toolkit.getDefaultToolkit();
        java.awt.Dimension pantalla = toolkit.getScreenSize();

        javax.swing.ImageIcon iconoOriginal = new javax.swing.ImageIcon(getClass().getResource("/Imagenes/Logo2.png"));
        java.awt.Image imagenEscalada = iconoOriginal.getImage().getScaledInstance(
                pantalla.width,
                pantalla.height,
                java.awt.Image.SCALE_SMOOTH
        );
        jLabel2.setIcon(new javax.swing.ImageIcon(imagenEscalada));
    }

    private void configurarPantallaCompleta() {
        setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
    }

    private void iniciarAnimacionFadeIn() {
        setOpacity(0f);
        setVisible(true);

        Timer fadeTimer = new Timer(30, null);
        fadeTimer.addActionListener(e -> {
            float opacidadActual = getOpacity();
            if (opacidadActual < 1f) {
                float nuevaOpacidad = Math.min(opacidadActual + 0.05f, 1f);
                setOpacity(nuevaOpacidad);
            } else {
                fadeTimer.stop();
                esperarYAbrirMenu();
            }
        });
        fadeTimer.start();
    }

    private void esperarYAbrirMenu() {
        Timer esperaTimer = new Timer(4500, e -> abrirMenu());
        esperaTimer.setRepeats(false);
        esperaTimer.start();
    }

    private void abrirMenu() {
        Menu menu = new Menu();
        menu.setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
        menu.setVisible(true);
        dispose();
    }

