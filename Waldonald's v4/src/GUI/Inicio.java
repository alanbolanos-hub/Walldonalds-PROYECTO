    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String usuario = jTextField1.getText().trim();
        String contrasena = claveReal.trim();

        if (usuario.isEmpty() || contrasena.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Por favor ingresa usuario y contraseña.",
                    "Campos vacíos",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        String sql = "SELECT u.Usuario, u.Estado, r.Rol "
                + "FROM Usuarios u "
                + "INNER JOIN Roles r ON u.id_rol = r.ID_Rol "
                + "WHERE u.Usuario = ? AND u.Password = ?";

        Connection con = Conexion.getConexion();

        if (con == null) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo conectar a la base de datos.\nRevisa que MySQL esté encendido y los datos en Conexion.java.",
                    "Error de conexión",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        try (PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, usuario);
            ps.setString(2, contrasena);

            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    boolean activo = rs.getBoolean("Estado");
                    String rol = rs.getString("Rol");

                    if (!activo) {
                        JOptionPane.showMessageDialog(this,
                                "Este usuario está deshabilitado.",
                                "Acceso denegado",
                                JOptionPane.ERROR_MESSAGE);
                        return;
                    }

                    if (rol.equals("Administrador")) {
                        Administrador ventana = new Administrador();
                        ventana.setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
                        ventana.setVisible(true);
                        this.dispose();

                    } else if (rol.equals("Cajero")) {
                        Cajero ventana = new Cajero();
                        ventana.setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
                        ventana.setVisible(true);
                        this.dispose();

                    } else {
                        JOptionPane.showMessageDialog(this,
                                "El usuario tiene un rol no reconocido.",
                                "Acceso denegado",
                                JOptionPane.ERROR_MESSAGE);
                    }

                } else {
                    JOptionPane.showMessageDialog(this,
                            "Usuario o contraseña incorrectos.",
                            "Acceso denegado",
                            JOptionPane.ERROR_MESSAGE);
                    jTextField2.setText("");
                    claveReal = "";
                }
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error al consultar la base de datos:\n" + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

