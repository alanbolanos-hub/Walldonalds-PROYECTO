    private void configurarCamposLogin() {

        jTextField1.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                if (jTextField1.getText().equals(PLACEHOLDER_USUARIO)) {
                    jTextField1.setText("");
                }
            }
        });

        jTextField2.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                if (jTextField2.getText().equals(PLACEHOLDER_PASSWORD)) {
                    jTextField2.setText("");
                    claveReal = "";
                }
            }
        });

        jTextField2.addKeyListener(new java.awt.event.KeyAdapter() {
            @Override
            public void keyTyped(java.awt.event.KeyEvent evt) {
                char c = evt.getKeyChar();

                if (c == '\b') {
                    if (claveReal.length() > 0) {
                        claveReal = claveReal.substring(0, claveReal.length() - 1);
                    }
                } else if (!Character.isISOControl(c)) {
                    claveReal += c;
                }

                StringBuilder asteriscos = new StringBuilder();
                for (int i = 0; i < claveReal.length(); i++) {
                    asteriscos.append('*');
                }

                jTextField2.setText(asteriscos.toString());
                evt.consume();
            }
        });
    }

