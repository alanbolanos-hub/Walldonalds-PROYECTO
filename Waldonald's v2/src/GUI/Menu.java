    private void iniciarCarrusel() {

        seleccionarImagenesPorHora();

        javax.swing.Timer timerCarrusel = new javax.swing.Timer(3000, e -> {

            if (imagenesActuales == null || imagenesActuales.length == 0) {
                return;
            }

            imagenActual++;

            if (imagenActual >= imagenesActuales.length) {
                imagenActual = 0;
            }

            cambiarImagen();
        });

        timerCarrusel.start();
    }

    private void iniciarVerificacionHorario() {

        javax.swing.Timer timerHorario = new javax.swing.Timer(30000, e -> {

            seleccionarImagenesPorHora();

        });

        timerHorario.start();
    }

    private void seleccionarImagenesPorHora() {

        LocalTime hora = LocalTime.now();

        if (!hora.isBefore(LocalTime.of(4, 0))
                && !hora.isAfter(LocalTime.of(11, 30))) {

            imagenesActuales = imagenesManana;
            jLabel3.setText("Desayuno");

        } else if (!hora.isBefore(LocalTime.of(11, 31))
                && !hora.isAfter(LocalTime.of(17, 30))) {

            imagenesActuales = imagenesTarde;
            jLabel3.setText("Almuerzo");

        } else {

            imagenesActuales = imagenesNoche;
            jLabel3.setText("Cena");
        }

        imagenActual = 0;

        cambiarImagen();
    }

    private void cambiarImagen() {

        if (imagenesActuales == null || imagenesActuales.length == 0) {
            return;
        }

        java.net.URL url
                = getClass().getResource(imagenesActuales[imagenActual]);

        if (url == null) {
            System.out.println(
                    "No se encontró la imagen: "
                    + imagenesActuales[imagenActual]
            );
            return;
        }

        ImageIcon icono = new ImageIcon(url);

        Image imagen = icono.getImage().getScaledInstance(
                jLabel5.getWidth(),
                jLabel5.getHeight(),
                Image.SCALE_SMOOTH
        );

        jLabel5.setIcon(new ImageIcon(imagen));
    }

